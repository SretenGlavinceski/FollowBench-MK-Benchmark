# The tables of the paper (same numbering) and docs/RESULTS.md.
#   python scripts/make_tables.py

import collections
import csv
import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
METRICS_DIR = os.path.join(ROOT, "results", "metrics")
COMPARISON_FILE = os.path.join(ROOT, "judging", "parsed", "comparison.csv")
OUT_DIR = os.path.join(ROOT, "results", "tables")
RESULTS_MD = os.path.join(ROOT, "docs", "RESULTS.md")
FIGURES = "../results/figures/"

MODELS = ["qwen3.5-9b", "gemma-4-12b", "llama-3.1-8b", "domestic-yak-8b"]
NAMES = {"qwen3.5-9b": "Qwen3.5 9B", "gemma-4-12b": "Gemma 4 12B",
         "llama-3.1-8b": "Llama 3.1 8B", "domestic-yak-8b": "Domestic-Yak 8B"}
LANGS = ["en", "mk"]
CATEGORIES = ["content", "situation", "style", "format"]
LEVELS = [1, 2, 3, 4, 5]

MARKDOWN = []


def read_metrics(name):
    return list(csv.DictReader(open(os.path.join(METRICS_DIR, name), encoding="utf-8")))


def pct(value):
    return "%.1f" % (float(value) * 100)


def wilson(passed, n, z=1.96):
    p = passed / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return centre - half, centre + half


def add_table(name, title, header, rows, note=None, figure=None):
    with open(os.path.join(OUT_DIR, name), "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)
    print("wrote results/tables/" + name)
    if title:
        MARKDOWN.append("## " + title)
        MARKDOWN.append("")
    if note:
        MARKDOWN.append(note)
        MARKDOWN.append("")
    MARKDOWN.append("| " + " | ".join(header) + " |")
    MARKDOWN.append("|" + "|".join(["---"] * len(header)) + "|")
    for row in rows:
        MARKDOWN.append("| " + " | ".join(str(x) for x in row) + " |")
    MARKDOWN.append("")
    if figure:
        MARKDOWN.append("![%s](%s%s)" % (title, FIGURES, figure))
        MARKDOWN.append("")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    scores = read_metrics("response_scores.csv")
    summary = {}
    for row in read_metrics("summary_metrics.csv"):
        summary[(row["analysis"], row["model"], row["lang"])] = row
    level = {}
    for row in read_metrics("level_metrics.csv"):
        level[(row["analysis"], row["model"], row["lang"], int(row["level"]))] = row
    category = {}
    for row in read_metrics("category_metrics.csv"):
        category[(row["analysis"], row["model"], row["lang"], row["category"])] = row
    comparison = list(csv.DictReader(open(COMPARISON_FILE, encoding="utf-8")))

    # pass or fail per response, with truncated = fail
    passed = {}
    for row in scores:
        key = (row["model"], row["lang"], row["family_id"], int(row["level"]))
        if row["truncated"] == "True":
            passed[key] = 0
        else:
            passed[key] = int(row["hard"])
    families = sorted({key[2] for key in passed})

    MARKDOWN.extend(["# FollowBench-MK results", "",
                     "All tables and figures from the paper, generated by `scripts/make_tables.py` and "
                     "`scripts/make_figures.py`. HSR and SSR are in %, CSL in levels (0–5). "
                     "Analysis A counts truncated responses as failures; Analysis B leaves them out.", ""])

    # Table 6: main results with Wilson intervals from the real counts
    rows = []
    for model in MODELS:
        for lang in LANGS:
            a = summary[("A", model, lang)]
            b = summary[("B", model, lang)]
            n_passed = 0
            n_total = 0
            for family in families:
                for lv in LEVELS:
                    n_passed += passed[(model, lang, family, lv)]
                    n_total += 1
            low, high = wilson(n_passed, n_total)
            rows.append([NAMES[model], lang.upper(), b["n_responses"], pct(a["hsr"]),
                         "[%.1f, %.1f]" % (low * 100, high * 100), pct(a["ssr"]), "%.2f" % float(a["csl"])])
    add_table("table06_main_results.csv", "Main results (Table 6)",
              ["Model", "Lang", "Judged", "HSR (%)", "HSR 95% CI", "SSR (%)", "CSL"], rows,
              figure="fig2_en_vs_mk.png")

    # Table 7: paired English–Macedonian outcomes
    rows = []
    total = collections.Counter()
    for model in MODELS:
        outcomes = collections.Counter()
        for family in families:
            for lv in LEVELS:
                en = passed[(model, "en", family, lv)]
                mk = passed[(model, "mk", family, lv)]
                outcomes[(en, mk)] += 1
        total += outcomes
        rows.append([NAMES[model], outcomes[(1, 1)], outcomes[(1, 0)], outcomes[(0, 1)], outcomes[(0, 0)]])
    rows.append(["Total", total[(1, 1)], total[(1, 0)], total[(0, 1)], total[(0, 0)]])
    add_table("table07_paired_outcomes.csv", "Paired English–Macedonian outcomes (Table 7)",
              ["Model", "Both", "Only EN", "Only MK", "Neither"], rows,
              note="Each model has 100 prompt pairs; \"satisfied\" means all constraints were satisfied.")

    # Table 8: HSR by level and CSL
    rows = []
    for model in MODELS:
        for lang in LANGS:
            row = [NAMES[model], lang.upper()]
            for lv in LEVELS:
                row.append(pct(level[("A", model, lang, lv)]["hsr"]))
            row.append(pct(summary[("A", model, lang)]["hsr"]))
            row.append("%.2f" % float(summary[("A", model, lang)]["csl"]))
            rows.append(row)
    add_table("table08_hsr_by_level.csv", "Results by level (Table 8)",
              ["Model", "Lang"] + ["L%d" % lv for lv in LEVELS] + ["Avg", "CSL"], rows,
              note="HSR (%) by level and CSL, Analysis A, n = 20 per level.",
              figure="fig3_hsr_by_level.png")

    # SSR by level (Figure 5)
    rows = []
    for model in MODELS:
        for lang in LANGS:
            row = [NAMES[model], lang.upper()]
            for lv in LEVELS:
                row.append(pct(level[("A", model, lang, lv)]["ssr"]))
            row.append(pct(summary[("A", model, lang)]["ssr"]))
            rows.append(row)
    add_table("figure05_ssr_by_level.csv", "SSR by level (Figure 5)",
              ["Model", "Lang"] + ["L%d" % lv for lv in LEVELS] + ["Avg"], rows,
              figure="fig5_ssr_by_level.png")

    # Table 9: failure consistency
    rows = []
    for model in MODELS:
        row = [NAMES[model]]
        for lang in LANGS:
            failed = 0
            consistent = 0
            for family in families:
                chain = [passed[(model, lang, family, lv)] for lv in LEVELS]
                for i in range(4):
                    if chain[i] == 0:
                        failed += 1
                        if all(x == 0 for x in chain[i + 1:]):
                            consistent += 1
            row.append("%.1f%% (%d/%d)" % (100 * consistent / failed, consistent, failed))
        rows.append(row)
    add_table("table09_failure_consistency.csv", "Failure consistency (Table 9)",
              ["Model", "English", "Macedonian"], rows,
              note="Share of failed levels L1–L4 after which every later level of the same family also failed.")

    # Results by category (Figure 4), Analysis A and B
    rows = []
    for model in MODELS:
        for lang in LANGS:
            row = [NAMES[model], lang.upper()]
            for analysis in ["A", "B"]:
                for cat in CATEGORIES:
                    row.append(pct(category[(analysis, model, lang, cat)]["hsr"]))
            rows.append(row)
    header = ["Model", "Lang"]
    for analysis in ["A", "B"]:
        for cat in CATEGORIES:
            header.append("HSR %s %s" % (cat, analysis))
    add_table("figure04_hsr_by_category.csv", "Results by category (Figure 4)", header, rows,
              note="HSR (%) per category, 25 prompts per cell. A: truncated = fail. B: truncated left out.",
              figure="fig4_category_heatmap.png")

    # Truncation (Figure 1 and Section 5.1)
    by_model = collections.Counter()
    by_level = collections.Counter()
    for row in scores:
        if row["truncated"] == "True":
            by_model[(row["model"], row["lang"])] += 1
            by_level[(row["lang"], int(row["level"]))] += 1
    rows = []
    for model in MODELS:
        rows.append([NAMES[model], by_model[(model, "en")], by_model[(model, "mk")]])
    rows.append(["Total", sum(by_model[(m, "en")] for m in MODELS), sum(by_model[(m, "mk")] for m in MODELS)])
    add_table("figure01_truncation_by_model.csv", "Truncated responses (Figure 1)",
              ["Model", "English", "Macedonian"], rows,
              note="Responses that reached the 2,048-token limit, out of 100 per model and language.")
    rows = []
    for lang in LANGS:
        rows.append([lang.upper()] + [by_level[(lang, lv)] for lv in LEVELS])
    add_table("truncation_by_level.csv", None, ["Lang"] + ["L%d" % lv for lv in LEVELS], rows,
              note="By level, over all models:")
    MARKDOWN.append("![Truncated responses](%sfig1_truncation.png)" % FIGURES)
    MARKDOWN.append("")

    # each judge's verdict per response: satisfied only if every criterion is YES
    verdict_a = collections.defaultdict(lambda: True)
    verdict_b = collections.defaultdict(lambda: True)
    packet_info = {}
    for row in comparison:
        packet = row["packet_id"]
        verdict_a[packet] = verdict_a[packet] and row["judge_A"] == "YES"
        verdict_b[packet] = verdict_b[packet] and row["judge_B"] == "YES"
        packet_info[packet] = (row["model"], row["lang"])

    # Table 5: judge agreement
    rows = []
    for label, lang in [("English", "en"), ("Macedonian", "mk"), ("All", None)]:
        n_packets = 0
        n_same = 0
        for packet in packet_info:
            if lang is not None and packet_info[packet][1] != lang:
                continue
            n_packets += 1
            if verdict_a[packet] == verdict_b[packet]:
                n_same += 1
        rows.append([label, n_packets, n_same, "%.1f%%" % (100 * n_same / n_packets)])
    add_table("table05_judge_agreement.csv", "Judge agreement (Table 5)",
              ["Group", "Judged responses", "Same verdict", "Agreement"], rows,
              note="Agreement between the two judges on whether a response satisfied all of its criteria.")

    # Table 10: robustness, with each judge's decisions alone (truncated = fail)
    passed_a = collections.Counter()
    passed_b = collections.Counter()
    for packet, (model, lang) in packet_info.items():
        passed_a[(model, lang)] += verdict_a[packet]
        passed_b[(model, lang)] += verdict_b[packet]
    rows = []
    for model in MODELS:
        n = {}
        for lang in LANGS:
            n[lang] = int(summary[("A", model, lang)]["n_responses"])
        rows.append([NAMES[model],
                     "%s / %s" % (pct(summary[("A", model, "en")]["hsr"]), pct(summary[("A", model, "mk")]["hsr"])),
                     "%.1f / %.1f" % (100 * passed_a[(model, "en")] / n["en"], 100 * passed_a[(model, "mk")] / n["mk"]),
                     "%.1f / %.1f" % (100 * passed_b[(model, "en")] / n["en"], 100 * passed_b[(model, "mk")] / n["mk"]),
                     "%s / %s" % (pct(summary[("B", model, "en")]["hsr"]), pct(summary[("B", model, "mk")]["hsr"]))])
    add_table("table10_robustness.csv", "Robustness checks (Table 10)",
              ["Model", "Final", "ChatGPT only", "Claude only", "Analysis B"], rows,
              note="HSR (%) English / Macedonian. The first three columns use Analysis A; "
                   "\"ChatGPT only\" and \"Claude only\" use one judge's decisions for every criterion.")

    # Table 12: Analysis B
    rows = []
    for model in MODELS:
        for lang in LANGS:
            b = summary[("B", model, lang)]
            star = "*" if int(b["csl_families"]) < 10 else ""
            rows.append([NAMES[model], lang.upper(), b["n_responses"], pct(b["hsr"]), pct(b["ssr"]),
                         "%.2f (%s)%s" % (float(b["csl"]), b["csl_families"], star)])
    add_table("table12_analysis_b.csv", "Analysis B: truncated responses left out (Table 12)",
              ["Model", "Lang", "Judged", "HSR (%)", "SSR (%)", "CSL (families)"], rows,
              note="\\* fewer than 10 families.", figure="fig6_analysis_a_vs_b.png")

    with open(RESULTS_MD, "w", encoding="utf-8") as f:
        f.write("\n".join(MARKDOWN))
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
